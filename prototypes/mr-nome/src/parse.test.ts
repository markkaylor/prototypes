/**
 * The phrase corpus: what people say → what Mr. Nome should understand.
 * Expected values are the step chips joined with " · ", plus "? <leftover>" for anything not understood.
 * Add phrasings here first, watch them fail, then teach the rules.
 */
import { expect, test } from "vitest"
import { describe as label, parse } from "./parse"

const read = (s: string) =>
  parse(s).clauses.flatMap((c) => [...c.steps.map(label), ...(c.leftover ? [`? ${c.leftover}`] : [])]).join(" · ")

